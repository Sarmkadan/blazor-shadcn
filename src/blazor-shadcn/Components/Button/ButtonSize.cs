namespace BlazorShadcn.Components;

/// <summary>
/// Size of a <see cref="Button"/>, matching the sizes of shadcn/ui's <c>buttonVariants</c>.
/// </summary>
public enum ButtonSize
{
    /// <summary>Standard height and horizontal padding.</summary>
    Default,

    /// <summary>Compact button for dense layouts.</summary>
    Sm,

    /// <summary>Large button with generous padding.</summary>
    Lg,

    /// <summary>Square button sized for a single icon.</summary>
    Icon,
}
